import { test, expect } from '@playwright/test'

test.skip(!process.env.E2E_BASE_URL, 'Cần môi trường demo')

test('soạn mẫu hoá đơn HTML, xem nhanh, chọn cho hợp đồng hoặc kỳ hóa đơn', async ({ page }) => {
  const name = `Mẫu kiểm thử ${Date.now()}`
  await page.goto('/login')
  await page.getByRole('button', { name: /^Admin/ }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
  await page.goto('/templates')
  await page.getByRole('button', { name: 'Soạn mẫu mới' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('Tên mẫu').fill(name)
  await dialog.getByRole('button', { name: 'Hiện đại' }).click()
  await dialog.getByRole('button', { name: 'Xem trước PDF' }).click()
  const viewer = page.getByRole('dialog', { name: 'Xem trước mẫu' })
  await expect(viewer.locator('iframe')).toBeVisible({ timeout: 30_000 })
  await viewer.getByRole('button', { name: 'Đóng' }).click()
  await expect(viewer).toBeHidden()
  await dialog.getByRole('button', { name: 'Lưu' }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByText(name)).toBeVisible()
  await page.goto('/contracts/new')
  const invoiceTemplate = page.getByLabel('Mẫu hóa đơn', { exact: true })
  await invoiceTemplate.click()
  await expect(page.getByRole('option').filter({ hasText: name })).toHaveCount(1)
  await expect(page.getByRole('option').first()).toContainText('Theo mặc định hệ thống')
  await page.keyboard.press('Escape')
  await expect(invoiceTemplate).toContainText('Theo mặc định hệ thống')
  await page.goto('/invoices?view=draft')
  const invoice = page.locator('a[href^="/invoices/"]').filter({ hasNotText: 'Tạo' }).first()
  test.skip(await invoice.count() === 0, 'Cần một hóa đơn demo')
  await invoice.click()
  // Mẫu hoá đơn chỉ đổi trong sửa hợp đồng, trang hoá đơn không còn ô chọn mẫu
  await expect(page.getByLabel('Mẫu hóa đơn kỳ này')).toHaveCount(0)
  await page.goto('/templates')
  const row = page.getByRole('listitem').filter({ hasText: name })
  // bản xem dựng sẵn hiện ngay trong mục của mẫu (từ 2 mẫu trở lên phải bấm tên mẫu để mở)
  const toggle = row.getByRole('button', { name, exact: false }).first()
  if (await toggle.getAttribute('aria-expanded') === 'false') await toggle.click()
  await expect(row.locator('iframe')).toBeVisible({ timeout: 30_000 })
  await row.getByRole('button', { name: 'Xoá' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Xoá' }).click()
  await expect(page.getByText(name)).toBeHidden()
})

test('danh sách mẫu hoá đơn dùng được trên điện thoại', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/login')
  await page.getByRole('button', { name: /^Admin/ }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
  await page.goto('/templates')
  await expect(page.getByRole('button', { name: 'Soạn mẫu mới' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
