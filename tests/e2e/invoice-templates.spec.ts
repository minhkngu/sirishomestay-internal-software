import { test, expect } from '@playwright/test'
import { createCanvas } from '@napi-rs/canvas'

test.skip(!process.env.E2E_BASE_URL, 'Cần môi trường demo')

test('tạo mẫu, chỉnh bố cục và chọn cho hợp đồng hoặc kỳ hóa đơn', async ({ page }) => {
  const name = `Mẫu kiểm thử ${Date.now()}`
  await page.goto('/login')
  await page.getByRole('button', { name: /^Admin/ }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
  await page.goto('/templates')
  await page.getByRole('button', { name: 'Tạo mẫu mới' }).click()
  await page.getByLabel('Tên mẫu hóa đơn').fill(name)
  await page.getByLabel('Tên thương hiệu').fill('SIRIS DEMO')
  const canvas = createCanvas(8, 8)
  canvas.getContext('2d').fillRect(0, 0, 8, 8)
  await page.getByLabel('Logo hóa đơn').setInputFiles({ name: 'logo.png', mimeType: 'image/png', buffer: canvas.toBuffer('image/png') })
  await expect(page.getByAltText('Logo đang chọn')).toBeVisible()
  await page.getByLabel('Tiêu đề hóa đơn').fill('HÓA ĐƠN KIỂM THỬ')
  await page.getByLabel('Nội dung chân trang').fill('Cảm ơn quý khách')
  await page.getByRole('button', { name: 'Đưa Bảng khoản thu lên' }).click()
  await page.getByRole('button', { name: 'Lưu mẫu', exact: true }).click()
  await expect(page.getByText('Đã lưu mẫu', { exact: true })).toBeVisible()
  await page.goto('/contracts/new')
  await expect(page.getByLabel('Mẫu hóa đơn', { exact: true }).locator('option').filter({ hasText: name })).toHaveCount(1)
  await expect(page.getByLabel('Mẫu hóa đơn', { exact: true })).toHaveValue('')
  await expect(page.getByLabel('Mẫu hóa đơn', { exact: true }).locator('option').first()).toContainText('Theo mặc định hệ thống')
  await page.goto('/invoices?view=draft')
  const invoice = page.locator('a[href^="/invoices/"]').filter({ hasNotText: 'Tạo' }).first()
  test.skip(await invoice.count() === 0, 'Cần một hóa đơn demo')
  await invoice.click()
  const picker = page.getByLabel('Mẫu hóa đơn kỳ này')
  const previous = await picker.inputValue()
  const option = picker.locator('option').filter({ hasText: name })
  const id = await option.getAttribute('value')
  await picker.selectOption(id!)
  await expect(picker).toHaveValue(id!)
  await page.reload()
  await expect(page.getByLabel('Mẫu hóa đơn kỳ này')).toHaveValue(id!)
  await page.getByRole('button', { name: 'Xem PDF' }).click()
  await expect(page.getByTitle('Hóa đơn PDF')).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByLabel('Mẫu hóa đơn kỳ này').selectOption(previous)
  await expect(page.getByLabel('Mẫu hóa đơn kỳ này')).toHaveValue(previous)
  await page.goto('/templates')
  await page.getByLabel('Chọn mẫu để chỉnh sửa').selectOption(id!)
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Xóa mẫu' }).click()
  await expect(page.getByText('Đã xóa mẫu')).toBeVisible()
})

test('màn hình chỉnh mẫu dùng được trên điện thoại', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/login')
  await page.getByRole('button', { name: /^Admin/ }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
  await page.goto('/templates')
  await expect(page.getByLabel('Tên mẫu hóa đơn')).toBeVisible()
  await expect(page.getByLabel('Logo hóa đơn')).toBeVisible()
  await expect(page.getByText('Xem trước bố cục')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
})
