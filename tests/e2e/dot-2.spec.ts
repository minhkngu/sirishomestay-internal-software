import { test, expect, type Page } from '@playwright/test'
import { createTempLease, fillMeterReadings, meterValue } from './helpers'

test.skip(!process.env.E2E_BASE_URL, 'Cần E2E_BASE_URL trỏ tới môi trường thử có dữ liệu mẫu')
async function login(page: Page, name: RegExp) {
  await page.goto('/login')
  await page.getByRole('button', { name }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
}

test('Hùng xem trạng thái phòng mà không thấy tên khách hay tiền', async ({ page }) => {
  await login(page, /^Hùng/)
  await page.goto('/facilities')
  await page.getByRole('link', { name: /Bình Thạnh/ }).first().click()
  const occupied = page.locator('a[href^="/rooms/"]').filter({ hasText: /Đang ở|Sắp trả/ }).first()
  await expect(occupied).toBeVisible()
  await occupied.click()
  await expect(page.getByRole('heading', { name: /^Phòng / })).toBeVisible()
  await expect(page.getByText(/Đang ở|Sắp trả/).first()).toBeVisible()
  await expect(page.getByText('Thông tin thanh toán')).toHaveCount(0)
  await expect(page.getByText('Người ở:', { exact: false })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Hợp đồng phòng' })).toHaveCount(0)
})

test('nhập và chuyển vật tư theo số lượng', async ({ page }) => {
  await login(page, /^Admin/)
  await page.goto('/assets')
  const uniqueName = `Bóng đèn thử ${Date.now()}`
  await page.getByLabel('Cơ sở vật tư').selectOption({ label: 'Thảo Điền' })
  await page.getByLabel('Tên vật tư').fill(uniqueName)
  await page.getByLabel('Đơn vị', { exact: true }).fill('cái')
  await page.getByLabel('Loại vật tư').fill('Điện')
  await page.getByRole('button', { name: 'Thêm vật tư' }).click()
  // Vật tư mới chưa có tồn kho nên chưa có dòng trong bảng; kiểm tra nó có trong danh sách chọn
  const itemOption = page.getByLabel('Vật tư', { exact: true }).locator('option').filter({ hasText: uniqueName })
  await expect(itemOption).toHaveCount(1)
  await page.getByLabel('Vật tư', { exact: true }).selectOption((await itemOption.getAttribute('value'))!)
  await page.getByLabel('Vị trí đích').selectOption({ label: 'Kho' })
  await page.getByLabel('Số lượng').fill('20')
  await page.getByRole('button', { name: 'Lưu', exact: true }).last().click()
  // Bảng vật tư phân trang 15 dòng: mở rộng để thấy dòng vừa tạo
  await page.getByLabel('Số dòng').first().selectOption('100')
  await expect(page.getByRole('row').filter({ hasText: uniqueName })).toContainText('20')
  await page.getByLabel('Thao tác').selectOption('move')
  await page.getByLabel('Vị trí nguồn').selectOption({ label: 'Kho' })
  const target = page.getByLabel('Vị trí đích')
  const roomValue = await target.locator('option').filter({ hasText: 'Phòng' }).first().getAttribute('value')
  expect(roomValue).toBeTruthy()
  await target.selectOption(roomValue!)
  await page.getByLabel('Số lượng').fill('3')
  await page.getByRole('button', { name: 'Lưu', exact: true }).last().click()
  await expect(page.getByRole('row').filter({ hasText: uniqueName }).filter({ hasText: 'Kho' })).toContainText('17')
  await expect(page.getByRole('row').filter({ hasText: uniqueName }).filter({ hasText: 'Phòng' })).toContainText('3')
})

test('tạo cọc, chuyển thành hợp đồng, xuất Word và bàn giao', async ({ page }) => {
  test.setTimeout(300_000) // luồng dài nhiều trang, môi trường thử chậm
  await login(page, /^Admin/)
  await page.goto('/contracts/new?kind=deposit')
  const roomOption = page.locator('#room option').filter({ hasText: 'Trống' }).first()
  const roomId = await roomOption.getAttribute('value')
  expect(roomId).toBeTruthy()
  await page.locator('#room').selectOption(roomId!)
  const tenantOption = page.locator('#tenant option').filter({ hasText: 'Nguyễn Văn An' }).first()
  await page.locator('#tenant').selectOption((await tenantOption.getAttribute('value'))!)
  await page.getByLabel('Tiền cọc giữ chỗ (VND)').fill('5000000')
  await page.getByLabel('Giá thuê thoả thuận (VND/tháng)').fill('9000000')
  await page.getByLabel('Ngày vào ở dự kiến').fill('2026-12-01')
  await page.getByRole('button', { name: 'Tạo hợp đồng cọc' }).click()
  await expect(page).toHaveURL(/\/contracts\/[a-f0-9-]+$/)
  const depositUrl = page.url()
  await page.goto(`/rooms/${roomId}`)
  await expect(page.getByText('Đã cọc', { exact: true })).toBeVisible()
  await page.goto(depositUrl)
  await page.getByRole('link', { name: 'Chuyển thành hợp đồng thuê' }).click()
  await page.getByRole('button', { name: '+12 tháng' }).click()
  await fillMeterReadings(page)
  await page.getByRole('button', { name: 'Tạo hợp đồng thuê' }).click()
  await expect(page).toHaveURL(/\/contracts\/[a-f0-9-]+$/, { timeout: 60_000 })
  const leaseUrl = page.url()
  await page.getByRole('tab', { name: 'Giấy tờ' }).click()
  const download = page.waitForEvent('download', { timeout: 20000 })
  await page.getByRole('button', { name: 'Xuất Word' }).click()
  expect((await download).suggestedFilename()).toMatch(/\.docx$/i)
  await page.locator('section', { hasText: 'Trạng thái ký' }).locator('input[type=file]').setInputFiles({ name: 'ban-da-ky.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n%%EOF') })
  await expect(page.getByRole('link', { name: 'Xem bản đã ký' })).toBeVisible()
  await page.getByRole('tab', { name: 'Bàn giao' }).click()
  await page.getByRole('button', { name: 'Check-in', exact: true }).click()
  await expect(page).toHaveURL(/\/handovers\//)
  await page.getByRole('button', { name: 'Hoàn tất' }).click()
  await expect(page.getByText('Đã hoàn tất biên bản')).toBeVisible()
  await page.goto(leaseUrl)
  await page.getByRole('tab', { name: 'Bàn giao' }).click()
  await page.getByRole('button', { name: 'Check-out', exact: true }).click()
  await expect(page).toHaveURL(/\/handovers\//)
  const readings = page.getByLabel(/^Chỉ số /)
  for (let i = 0; i < await readings.count(); i++) await readings.nth(i).fill(String(meterValue()))
  await page.getByRole('button', { name: 'Hoàn tất' }).click()
  await expect(page.getByText('Đã hoàn tất biên bản')).toBeVisible()
})

test('chuyển hai tài sản mới từ kho vào phòng', async ({ page }) => {
  await login(page, /^Admin/)
  await page.goto('/assets')
  const prefix = `E2E${Date.now()}`
  for (const suffix of ['A', 'B']) {
    await page.getByRole('button', { name: 'Thêm tài sản' }).click()
    await page.getByLabel('Cơ sở', { exact: true }).selectOption({ label: 'Thảo Điền' })
    await page.getByLabel('Mã tài sản').fill(prefix + suffix)
    await page.getByLabel('Tên tài sản').fill('Tài sản kiểm thử')
    await page.getByLabel('Giá trị', { exact: true }).fill('100000')
    await page.getByRole('button', { name: 'Lưu', exact: true }).first().click()
    // Bảng tài sản phân trang: lọc theo mã vừa tạo để chắc chắn thấy dòng
    await page.getByLabel('Tìm tài sản').fill(prefix + suffix)
    await expect(page.getByRole('link', { name: prefix + suffix, exact: true })).toBeVisible()
  }
  await page.getByLabel('Tìm tài sản').fill(prefix)
  await expect(page.getByRole('link', { name: prefix + 'A', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: prefix + 'B', exact: true })).toBeVisible()
  await page.getByLabel(`Chọn ${prefix}A`).check()
  await page.getByLabel(`Chọn ${prefix}B`).check()
  await page.getByRole('button', { name: 'Chuyển 2 tài sản' }).click()
  const dialog = page.getByRole('dialog', { name: 'Chuyển tài sản' })
  const option = dialog.getByLabel('Nơi đến').locator('option').filter({ hasText: 'Phòng' }).first()
  const roomLabel = await option.innerText()
  await dialog.getByLabel('Nơi đến').selectOption((await option.getAttribute('value'))!)
  await dialog.getByLabel('Lý do').fill('Kiểm thử')
  await dialog.getByRole('button', { name: 'Chuyển', exact: true }).click()
  await expect(dialog).toBeHidden()
  await expect(page.getByRole('row').filter({ hasText: prefix + 'A' })).toContainText(roomLabel)
  await expect(page.getByRole('row').filter({ hasText: prefix + 'B' })).toContainText(roomLabel)
})

test('ghi chỉ số điện theo dòng phí và báo chỉ số giảm', async ({ page }) => {
  test.setTimeout(300_000)
  // Đồng hồ Điện là đồng hồ theo dòng phí của hợp đồng: tạo hợp đồng tạm rồi ghi chỉ số cho phòng đó (kỳ 12/2026)
  const { roomCode } = await createTempLease(page)
  await page.goto('/meters')
  await page.getByLabel('Cơ sở', { exact: true }).selectOption({ label: 'Thảo Điền' })
  await page.getByLabel('Kỳ', { exact: true }).fill('2026-12')
  await page.getByRole('button', { name: 'Xem bảng ghi' }).click()
  const reading = page.getByLabel(`Điện phòng ${roomCode}`, { exact: true })
  const box = reading.locator('xpath=..')
  const previous = Number((await box.innerText()).match(/Chỉ số cũ:\s*(\d+)/)![1])
  expect(previous).toBeGreaterThan(0)
  await reading.fill('0')
  await page.getByRole('button', { name: 'Lưu chỉ số' }).click()
  await expect(box.getByText('Chỉ số mới nhỏ hơn chỉ số cũ')).toBeVisible()
  await reading.fill(String(previous + 1))
  await page.getByRole('button', { name: 'Lưu chỉ số' }).click()
  await expect(page.getByText('Đã lưu 1 chỉ số', { exact: true })).toBeVisible()
})
