import { test, expect, type Page } from '@playwright/test'
import { fillMeterReadings, meterValue, pickDate, pickTerm } from './helpers'

test.skip(!process.env.E2E_BASE_URL, 'Cần E2E_BASE_URL trỏ tới môi trường thử có dữ liệu mẫu')
async function login(page: Page, name: RegExp) {
  await page.goto('/login')
  await page.getByRole('button', { name }).click()
  await expect(page.getByRole('heading', { name: 'Nhắc việc' })).toBeVisible()
}

test('tạo hoá đơn hàng loạt → sửa kỳ → duyệt → thu một phần', async ({ page }) => {
  await login(page, /^Admin/)
  await page.goto('/invoices?view=draft')
  await page.waitForLoadState('networkidle')
  if (await page.getByText('Không có hoá đơn nào').isVisible()) {
    await page.goto('/invoices/generate')
    await page.waitForLoadState('networkidle')
    await page.getByRole('button', { name: 'Xem trước' }).click()
    const create = page.getByRole('button', { name: /^Tạo \d+ hoá đơn nháp$/ })
    await expect(create).toBeVisible()
    await expect(create).toBeEnabled()
    await create.click()
    await expect(page).toHaveURL(/view=draft/)
  }
  await page.locator('a[href^="/invoices/"]').filter({ hasNotText: 'Tạo' }).first().click()
  await page.waitForLoadState('networkidle')
  await expect(page.getByText('Nháp').first()).toBeVisible()
  // sửa kỳ thành 3 tháng rồi áp dụng
  const start = await page.getByLabel('Từ').inputValue()
  const [y, m] = start.split('-').map(Number)
  const end = new Date(Date.UTC(y, m + 2, 0)).toISOString().slice(0, 10)
  await page.getByLabel('Đến').fill(end)
  await page.getByRole('button', { name: 'Áp dụng kỳ' }).click()
  await expect(page.getByText('Đã tính lại tiền phòng và phí cố định')).toBeVisible()
  await page.getByRole('button', { name: 'Duyệt hoá đơn' }).click()
  await expect(page.getByText('Chưa thu').first()).toBeVisible()
  await page.getByRole('button', { name: 'Ghi thu' }).click()
  await page.getByLabel('Số tiền').fill('1000000')
  await page.getByRole('button', { name: 'Lưu khoản thu' }).click()
  await expect(page.getByText('Thu một phần').first()).toBeVisible()
})

test('luồng xuyên suốt: tạo khách → cọc → hợp đồng thuê → check-in → hoá đơn đầu tiên nháp', async ({ page }) => {
  test.setTimeout(300_000) // luồng dài nhiều trang, môi trường thử chậm
  await login(page, /^Admin/)
  const name = `Khách luồng ${Date.now()}`
  await page.goto('/tenants/new'); await page.waitForLoadState('networkidle')
  await page.getByLabel('Họ tên', { exact: true }).fill(name)
  await page.getByLabel('Quốc tịch').fill('Mỹ')
  await page.getByLabel('Số passport').fill(`FLOW${Date.now()}`)
  await page.getByLabel('Số điện thoại', { exact: true }).fill(`+1${String(Date.now()).slice(-10)}`)
  await page.getByRole('button', { name: 'Tạo khách' }).click()
  await expect(page).toHaveURL(/\/tenants\/[a-f0-9-]+$/)

  await page.goto('/contracts/new?kind=deposit'); await page.waitForLoadState('networkidle')
  await page.getByLabel('Toà', { exact: true }).click()
  await page.getByRole('option', { name: /Bình Thạnh/ }).first().click()
  await page.getByLabel('Phòng', { exact: true }).click()
  const roomOption = page.getByRole('option').filter({ hasText: 'Trống' }).first()
  await expect(roomOption).toBeVisible()
  const facilityName = 'Bình Thạnh'
  await roomOption.click()
  await page.getByLabel('Bên thuê', { exact: true }).click()
  await page.getByPlaceholder('Tìm theo tên hoặc số điện thoại…').fill(name)
  await page.getByRole('option').filter({ hasText: name }).first().click()
  await page.getByLabel('Tiền cọc giữ chỗ (VND)').fill('5000000')
  await page.getByLabel('Giá thuê thoả thuận (VND/tháng)').fill('9000000')
  await pickDate(page, 'Ngày vào ở dự kiến', '2026-12-01')
  await page.getByRole('button', { name: 'Tạo hợp đồng cọc' }).click()
  await expect(page).toHaveURL(/\/contracts\/[a-f0-9-]+$/)
  await page.getByRole('link', { name: 'Chuyển thành hợp đồng thuê' }).click()
  await pickTerm(page, 12)
  await fillMeterReadings(page)
  await page.getByRole('button', { name: 'Tạo hợp đồng thuê' }).click()
  await expect(page).toHaveURL(/\/contracts\/[a-f0-9-]+$/, { timeout: 60_000 })
  const leaseUrl = page.url()

  await page.getByRole('button', { name: 'Check-in', exact: true }).click()
  await expect(page).toHaveURL(/\/handovers\//)
  await page.getByRole('button', { name: 'Hoàn tất' }).click()
  await expect(page.getByText('Đã hoàn tất biên bản')).toBeVisible()

  // Hợp đồng không tự sinh hoá đơn: tạo hàng loạt cho cơ sở của phòng, kỳ 12/2026 (tháng bắt đầu hợp đồng)
  await page.goto('/invoices/generate')
  await page.getByLabel('Cơ sở').selectOption({ label: facilityName })
  await page.getByLabel('Kỳ (tháng)').fill('2026-12')
  await page.getByRole('button', { name: 'Xem trước' }).click()
  const createDrafts = page.getByRole('button', { name: /^Tạo \d+ hoá đơn nháp$/ })
  await expect(createDrafts).toBeEnabled()
  await createDrafts.click()
  await expect(page).toHaveURL(/view=draft/)
  await page.getByLabel('Số dòng').click()
  await page.getByRole('option', { name: '100' }).click()
  await expect(page.getByRole('row').filter({ hasText: name })).toBeVisible()

  // thanh lý hợp đồng vừa tạo: hoá đơn thanh lý nháp, duyệt xong hợp đồng kết thúc
  await page.goto('/contracts'); await page.waitForLoadState('networkidle')
  await page.getByRole('row').filter({ hasText: name }).getByRole('button', { name: 'Thanh lý hợp đồng' }).click()
  await page.getByLabel('Ngày trả phòng').fill('2026-12-10')
  for (const input of await page.getByText('Chỉ số tại ngày trả phòng').locator('xpath=..').locator('input[type=number]').all()) await input.fill(String(meterValue()))
  await page.getByRole('button', { name: 'Xem trước tiền' }).click()
  await expect(page.getByText(/Hoá đơn thanh lý \(nháp\)/)).toBeVisible()
  await page.getByRole('button', { name: 'Lưu phụ lục' }).click()
  await expect(page.getByText('Đã lưu phụ lục')).toBeVisible()
  await page.goto('/invoices?view=draft')
  await page.getByRole('row').filter({ hasText: name }).filter({ hasText: /10\/12\/2026/ }).getByRole('link').click()
  await page.waitForLoadState('networkidle')
  await page.getByRole('button', { name: 'Duyệt hoá đơn' }).click()
  await expect(page.getByText(/Chưa thu|Chờ hoàn khách/).first()).toBeVisible()
  await page.goto(leaseUrl)
  await expect(page.getByText('Đã kết thúc')).toBeVisible()
})

test('tải hoá đơn dưới dạng PDF và ảnh', async ({ page }) => {
  await page.goto('/login')
  await page.getByRole('button', { name: /^Admin/ }).click()
  await expect(page).toHaveURL(/\/$/)
  await page.goto('/invoices')
  const detail = page.locator('main a[href^="/invoices/"]').filter({ hasNotText: 'Tạo' }).first()
  await expect(detail).toBeVisible()
  await detail.click()
  await page.getByRole('button', { name: 'Xem PDF' }).click()
  const dialog = page.getByRole('dialog', { name: 'Xem hóa đơn PDF' })
  await expect(dialog).toBeVisible()
  const preview = dialog.getByTitle('Hóa đơn PDF')
  const previewUrl = await preview.getAttribute('src')
  expect(previewUrl).toMatch(/^\/api\/files\/[^?]+\?inline=1$/)
  const pdf = await page.request.get(previewUrl!)
  expect(pdf.ok()).toBe(true)
  expect(pdf.headers()['content-type']).toContain('application/pdf')
  expect(pdf.headers()['content-disposition'] ?? '').not.toContain('attachment')
  await dialog.getByRole('button', { name: 'Đóng' }).click()
  for (const [label, extension] of [['Tải PDF', '.pdf'], ['Tải ảnh', '.png']] as const) {
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: label }).click()
    expect((await download).suggestedFilename()).toMatch(new RegExp(`${extension.replace('.', '\\.')}$`, 'i'))
  }
})

